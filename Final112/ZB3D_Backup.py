def manageZombies(app):
    for zombie in app.zombies:
        if zombie.alive:
            zombie.moveToward(app.player.x, app.player.y, app)
            if zombie.canAttack(app.player.x, app.player.y):
                app.player.health -= zombie.damage / app.stepsPerSecond
                app.damageFlash = 25
                app.biteSound.play(restart=True)
        else:
            app.score += 1
            app.spawnInterval = (min(app.spawnInterval-1, 60))
            app.player.ammo += 2

            app.maxZombies = 3 + app.score // 8

            if app.maxZombies>20:
                app.maxZombies = 20

    app.zombies = [z for z in app.zombies if z.alive]
    app.spawnTimer += 1
    if app.spawnTimer >= app.spawnInterval and len(app.zombies) < app.maxZombies:
        app.spawnTimer = 0
        assert(app.spawnPoints != []), 'No spawn points in map'
        spawnPt = random.choice(app.spawnPoints)
        spawnX, spawnY = spawnPt
        app.zombies.append(Zombie(spawnX, spawnY))

def isZombieLegal(app, zombie, radius=8):
    zx, zy = zombie.x, zombie.y
    for wall in app.map.walls:
        if (zx < min(wall.x1, wall.x2) - radius or
            zx > max(wall.x1, wall.x2) + radius or
            zy < min(wall.y1, wall.y2) - radius or
            zy > max(wall.y1, wall.y2) + radius or
            not wall.collision):
            continue
        if playerDistanceToWall(zx, zy, wall) < radius:
            return False
    return True


