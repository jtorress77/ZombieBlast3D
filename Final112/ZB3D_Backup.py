def drawZombies3D(app, rayList):
    horizon = app.height * 0.48
    px, py = app.player.x, app.player.y
    stripWidth = math.ceil(app.width/app.numRays)
    
    # Claude Sonnet suggested the lambda z: distance sort to draw farther away zombies first by Painter's algorithm
    sortedZombies = sorted(app.zombies,
                           key=lambda z: distance(px,py,z.x,z.y),
                           reverse=True)
    
    
    for zombie in sortedZombies:
        if not zombie.alive:
            continue
        drawZombie(app, zombie, rayList, horizon, px, py, stripWidth)

