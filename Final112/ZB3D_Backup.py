def damageZombies(app, spreadAngle=10, baseDamage = 65):
    px, py = app.player.x, app.player.y
    for zombie in app.zombies:
        if not zombie.alive:
            continue

        # angle check
        dx = zombie.x - px
        dy = zombie.y - py
        zombieDist = math.sqrt(dx**2 + dy**2)
        angleToZombie = math.atan2(dy, dx)
        angleDiff = angleToZombie - app.player.angle
        
        # normalize to -pi/pi
        while angleDiff > math.pi:  angleDiff -= 2*math.pi
        while angleDiff < -math.pi: angleDiff += 2*math.pi
        
        if abs(angleDiff) > math.radians(spreadAngle):
            continue
        
        # visibility check
        result = getRayHit(app, px, py, angleToZombie)
        if result != None:
            hitX, hitY, wall = result
            wallDist = distance(px, py, hitX, hitY)
            if wallDist < zombieDist:
                continue  # wall in the way
        
        # distance falloff damage
        maxDist = 1000
        spreadDropoffCoefficient = 2

        damage = random.randint(int(baseDamage * 0.8), baseDamage)
        damage *= (1-spreadDropoffCoefficient*angleDiff/spreadAngle)
        damageMult = max(0.1, 1 - zombieDist/maxDist)
        zombie.takeDamage(int(damage * damageMult))

