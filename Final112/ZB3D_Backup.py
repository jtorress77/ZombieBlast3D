def drawZombie(app, zombie, rayList, horizon, px, py, stripWidth):
    zombieScale = 1.5
    dx = zombie.x - px
    dy = zombie.y - py
    zombieDist = math.sqrt(dx**2 + dy**2)
    
    angleToZombie = math.atan2(dy, dx)
    angleDiff = angleToZombie - app.player.angle
    
    # Claude Sonnet 4.6 Suggested Angle Normalization on the next two lines
    while angleDiff > math.pi:  angleDiff -= 2*math.pi
    while angleDiff < -math.pi: angleDiff += 2*math.pi
    
    if abs(angleDiff) > app.fov/2:
        return
    
    # 
    screenX = int((angleDiff + app.fov/2) / app.fov * app.width)
    spriteHeight = int(app.scaleConstant * app.height / max(1, zombieDist)*zombieScale)
    spriteHeight = min(spriteHeight, int(app.height * 0.8)) 
    
    # Z check
    col = screenX // stripWidth
    if 0 <= col < len(rayList): # On Screen
        rayX, rayY, wall = rayList[col]
        wallDist = distance(px, py, rayX, rayY)
        if zombieDist > wallDist:
            return
    
    # Claude Sonnet 4.6 Coded the rest of this function
    spriteTop = horizon
    skinColor = rgb(100, 130, 80)
    darkSkin  = rgb(80,  110, 60)
    shirtColor = rgb(200,200, 200)
    pantsColor = rgb(66, 93, 140)

    
    headRadius  = spriteHeight // 8
    torsoWidth  = spriteHeight // 4
    torsoHeight = spriteHeight // 3
    armWidth    = spriteHeight // 9
    armHeight   = spriteHeight // 3
    legWidth    = spriteHeight // 7
    legHeight   = spriteHeight // 3
    neckWidth   = spriteHeight // 8
    neckHeight  = spriteHeight // 8

    # head
    drawCircle(screenX, spriteTop + headRadius, headRadius, fill=skinColor)
    
    # neck
    drawRect(screenX - neckWidth//2, spriteTop + headRadius*2,
             neckWidth, neckHeight, fill=darkSkin)
    
    # torso
    drawRect(screenX - torsoWidth//2, spriteTop + spriteHeight//4,
             torsoWidth, torsoHeight, fill=shirtColor)
    
    # arms
    drawRect(screenX - torsoWidth//2 - armWidth, spriteTop + spriteHeight//4,
             armWidth, armHeight, fill=darkSkin)
    drawRect(screenX + torsoWidth//2, spriteTop + spriteHeight//4,
             armWidth, armHeight, fill=darkSkin)
    
    # legs
    drawRect(screenX - legWidth - 2, spriteTop + spriteHeight//2,
             legWidth, legHeight, fill=pantsColor)
    drawRect(screenX + 2, spriteTop + spriteHeight//2,
             legWidth, legHeight, fill=pantsColor)

    # health bar
    barY = spriteTop - 10
    drawRect(screenX - spriteHeight//2, barY, spriteHeight, 6, fill='red')
    drawRect(screenX - spriteHeight//2, barY,
             int(spriteHeight * zombie.health/100), 6, fill='lime')

