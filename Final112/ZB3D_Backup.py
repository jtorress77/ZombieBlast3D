def isLegalPos(app, radius = 8):
    px, py = app.player.x, app.player.y
    for wall in app.map.walls:
        if (px < min(wall.x1, wall.x2) - radius or px > max(wall.x1, wall.x2) + radius or
            py < min(wall.y1, wall.y2) - radius or py > max(wall.y1, wall.y2) + radius):
            continue # skip walls we dont need to check based on bounding rectangle

        if wall.collision:
            if playerDistanceToWall(px, py, wall) < radius:
                 return False
    return True 

def castRays(app):
    dAngle = app.fov/app.numRays
    px, py = app.player.x, app.player.y
    startAngle = app.player.angle - app.fov/2
    hits = []
    for i in range(app.numRays):
        rayAngle = startAngle + i*dAngle
        result = getRayHit(app,px,py,rayAngle)
        if result != None:
            hitX, hitY, wall = result
            hits += [(hitX, hitY, wall)]
    return hits

def getRayHit(app, px, py, rayAngle):
    closestHit = None
    closestDist = None
    closestWall = None
    rdx, rdy = math.cos(rayAngle), math.sin(rayAngle)
    for wall in app.map.walls:
        result = getRayLineIntersection(px,py,rdx,rdy,wall)
        if result == None:
            continue
        rayX, rayY = result
        distToHit = distance(px,py,rayX,rayY)
        if closestHit == None or distToHit < closestDist:
            closestHit = rayX, rayY, wall
            closestDist = distToHit

    return closestHit

# AI Was used to assist with the logic for this function, particularly to use Cramer's rule, specifically the 0<=u<=1 check
def getRayLineIntersection(px, py, rdx, rdy, wall):
    # This logic is through solving the system of segment/ray equations in parametric form using cramer's rule
    # px + rdx*t = wx1 + wdx*u | @ Intersection Point
    # py + rdy*t = wy1 + wdy*u | @ Intersection Point
    # if 0 <= u <= 1 and t >= 0, then there is an intersection at (px + rdx*t, py + rdy*t)

    wx1, wy1, wx2, wy2 = wall.getCoords()
    wdx, wdy = wall.distX, wall.distY
    Det = cross(rdx, rdy, wdx, wdy)
    if almostEqual(Det, 0) : # Lines are || 
        return None 
    # Cramers Rule for this matrix:
    # | rdx - wdx | | t |  =  | wx1 - px |
    # | rdy - wdy | | u |  =  | wy1 - py |
    a1, b1, c1 = rdx, -wdx, wx1-px
    a2, b2, c2 = rdy, -wdy, wy1-py
    t, u = solveMatrixCramer(a1,b1,c1,a2,b2,c2)

    if 0<=u<=1 and t>=0:
        return px + rdx*t, py + rdy*t
    else:
        return None


def playerDistanceToWall(px, py, wall):
    # Point to line distance formula: https://en.wikipedia.org/wiki/Distance_from_a_point_to_a_line
    x1, y1, x2, y2 = wall.getCoords()
    dist = abs(px*(y2-y1) - py*(x2-x1) - cross(x1, y1, x2, y2)) /  wall.length
    return dist

# Math Functions:
def distance(x1, y1, x2, y2):
    return math.sqrt((x2-x1)**2 + (y2-y1)**2)

def dot(x1, y1, x2, y2):
    return x1*x2 + y1*y2

def cross(x1, y1, x2, y2):
    return x1*y2 - y1*x2

def almostEqual(x,y):
    return abs(x-y) < 10**-6

def solveMatrixCramer(a1, b1, c1, a2, b2, c2):
    # I Love Cramer's Rule!!! :)
    Det = cross(a1,b1,a2,b2)
    DetA = cross(c1,b1,c2,b2)
    DetB = cross(a1,c1,a2,c2)
    return DetA/Det , DetB/Det

